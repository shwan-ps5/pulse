#!/usr/bin/env python3
# Bakes printable ASCII from a TTF into render/fontatlas.h: an 8-bit coverage atlas plus advances.
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, out = sys.argv[1], sys.argv[2]
EM, CW, CH, COLS, BASE, PAD = 36, 40, 52, 16, 38, 2
font = ImageFont.truetype(ttf, EM)
glyphs = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0x410, 0x450)] + ['\u0401', '\u0451']
rows = (len(glyphs) + COLS - 1) // COLS
img = Image.new("L", (COLS * CW, rows * CH), 0)
d = ImageDraw.Draw(img)
adv = []
for i, g in enumerate(glyphs):
    x, y = (i % COLS) * CW, (i // COLS) * CH
    d.text((x + PAD, y + BASE), g, font=font, fill=255, anchor="ls")
    adv.append(round(font.getlength(g)))
px = img.tobytes()
with open(out, "w") as f:
    f.write("// Generated by tools/bakefont.py from %s. Do not edit.\n#pragma once\n#include <cstdint>\n\nnamespace fontatlas {\n" % ttf.split("/")[-1])
    f.write("constexpr int kEm = %d, kCellW = %d, kCellH = %d, kCols = %d, kBase = %d, kPad = %d, kW = %d, kH = %d, kFirst = 32, kCount = %d;\n" % (EM, CW, CH, COLS, BASE, PAD, COLS * CW, rows * CH, len(glyphs)))
    f.write("constexpr uint8_t kAdvance[%d] = {%s};\n" % (len(adv), ",".join(map(str, adv))))
    f.write("constexpr uint8_t kPixels[%d] = {\n" % len(px))
    for i in range(0, len(px), 32):
        f.write(",".join(map(str, px[i:i+32])) + ",\n")
    f.write("};\n}  // namespace fontatlas\n")
print(len(glyphs), COLS * CW, rows * CH)
